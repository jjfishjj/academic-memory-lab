create table if not exists public.rally_seasons (
  id text primary key check (char_length(id) between 2 and 12),
  title text not null check (char_length(title) between 1 and 60),
  status text not null check (status in ('scheduled', 'active', 'closed')),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  daily_run_limit integer not null default 5 check (daily_run_limit between 1 and 20),
  finalized_at timestamptz,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at)
);

